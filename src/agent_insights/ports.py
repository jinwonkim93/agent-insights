"""Application ports. New model servers and databases implement these contracts."""

from typing import Any, Protocol

from .domain import ClosedConversation


class Generator(Protocol):
    def generate_json(self, system: str, payload: dict) -> dict: ...


class Embedder(Protocol):
    @property
    def space_id(self) -> str: ...
    def embed(self, texts: list[str]) -> list[list[float]]: ...


class Clusterer(Protocol):
    def groups(self, vectors: list[list[float]], keys: list[str]) -> list[list[int]]: ...


class Repository(Protocol):
    def bots(self) -> list[tuple[str, str]]: ...
    def initialize(self) -> None: ...
    def check_ready(self) -> None: ...
    def enqueue(self, conversation: ClosedConversation) -> tuple[str, bool]: ...
    def claim(self, lease_seconds: int, max_attempts: int) -> dict | None: ...
    def renew_conversation(self, job: dict, seconds: int) -> bool: ...
    def renew_discovery(self, tenant: str, bot: str, token: str, seconds: int) -> bool: ...
    def topics(self, tenant: str, bot: str) -> list[dict]: ...
    def finish(self, job: dict, facets: list[dict]) -> None: ...
    def fail(self, job: dict, error: str, max_attempts: int) -> None: ...
    def pending(
        self, tenant: str, bot: str, limit: int, max_days: int, max_reviews: int
    ) -> list[dict]: ...
    def apply_discovery(
        self, tenant: str, bot: str, token: str, decisions: list[dict], max_topics: int
    ) -> dict: ...
    def acquire_discovery(self, tenant: str, bot: str, seconds: int) -> str | None: ...
    def release_discovery(self, tenant: str, bot: str, token: str) -> None: ...
    def list_topics(
        self, tenant: str, bot: str, start: Any, end: Any, limit: int
    ) -> list[dict]: ...
    def list_conversations(
        self,
        tenant: str,
        bot: str,
        start: Any,
        end: Any,
        topic_id: str | None,
        offset: int,
        limit: int,
    ) -> list[dict]: ...
    def conversation(self, tenant: str, bot: str, conversation_id: str) -> dict | None: ...
    def status(self, tenant: str, bot: str) -> dict: ...
